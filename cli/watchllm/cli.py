# ---------------------------------------------------------------------------
# init
# ---------------------------------------------------------------------------

def cmd_init(args: argparse.Namespace) -> int:
    """Generate a default .watchllm.yaml in the target directory."""
    target_dir = Path(args.directory).resolve()
    target_dir.mkdir(parents=True, exist_ok=True)
    config_path = target_dir / ".watchllm.yaml"

    if config_path.exists() and not args.force:
        if Console:
            console = Console()
            console.print(f"[bold yellow]Config already exists:[/bold yellow] {config_path}")
            console.print("Use [bold]--force[/bold] to overwrite.")
        else:
            print(f"Config already exists: {config_path}")
            print("Use --force to overwrite.")
        return 1

    config_path.write_text(DEFAULT_CONFIG, encoding="utf-8")
    if Console:
        Console().print(f"[bold green]Created:[/bold green] {config_path}")
    else:
        print(f"Created: {config_path}")
    return 0


# ---------------------------------------------------------------------------
# evaluate
# ---------------------------------------------------------------------------

def cmd_evaluate(args: argparse.Namespace) -> int:
    """Evaluate a file (or stdin) through the kernel."""
    cmd = ["watchllm-kernel", "check", "--json"]

    if args.stdin:
        cmd.append("--stdin")
    elif args.file:
        cmd += ["--filepath", args.file]
    else:
        print("Error: provide --file or --stdin", file=sys.stderr)
        return 2

    if args.mode:
        cmd += ["--mode", args.mode]
    if args.language:
        cmd += ["--language", args.language]

    try:
        result = subprocess.run(cmd, check=False)
        return result.returncode
    except FileNotFoundError:
        if Console:
            Console(stderr=True).print("[bold red]Error:[/bold red] watchllm-kernel not found. Run: [cyan]pip install -e d:/watchllm/kernel[/cyan]")
        else:
            print(
                "Error: watchllm-kernel not found. Run: pip install -e d:/watchllm/kernel",
                file=sys.stderr,
            )
        return 2


# ---------------------------------------------------------------------------
# status
# ---------------------------------------------------------------------------

def cmd_status(_args: argparse.Namespace) -> int:
    """Report installation health of all WatchLLM subsystems."""
    if not Console:
        print("Rich not installed. Run 'python d:/watchllm/bootstrap.py'")
        return 1

    console = Console()
    table = Table(title="WatchLLM Installation Status", show_header=True, header_style="bold magenta")
    table.add_column("Subsystem", style="cyan")
    table.add_column("Status", justify="center")
    table.add_column("Details", style="dim")
    
    all_ok = True
    for sub in SUBSYSTEMS:
        name = sub["name"]
        check = sub["check"]

        if check is None:
            table.add_row(name, "[yellow]SKIP[/yellow]", "No health-check defined")
            continue

        parts = check.split()
        executable = parts[0]
        found = shutil.which(executable) is not None

        if found:
            table.add_row(name, "[green]OK[/green]", "")
        else:
            table.add_row(name, "[red]MISSING[/red]", f"{executable} not found on PATH")
            all_ok = False

    console.print(table)
    if all_ok:
        console.print(Panel("[green]All subsystems OK.[/green]", expand=False))
    else:
        console.print(Panel("[red]Some subsystems are missing. Run: [bold]python d:/watchllm/bootstrap.py[/bold][/red]", expand=False))
    return 0 if all_ok else 1


# ---------------------------------------------------------------------------
# Parser
# ---------------------------------------------------------------------------

class FlashyParser(argparse.ArgumentParser):
    def print_help(self, file=None):
        if Console:
            console = Console(file=file or sys.stdout)
            console.print(ASCII_ART, justify="center")
            console.print()
            console.print("[bold bright_white]WatchLLM[/bold bright_white] — [italic]Deterministic runtime governance for autonomous coding agents.[/italic]", justify="center")
            console.print()
        super().print_help(file)

def build_parser() -> argparse.ArgumentParser:
    parser = FlashyParser(
        prog="watchllm",
        description="WatchLLM — Deterministic runtime governance for autonomous coding agents.",
    )
    parser.add_argument("--version", action="version", version="%(prog)s 0.1.3")
    sub = parser.add_subparsers(dest="command", metavar="command")

    # init
    init_p = sub.add_parser("init", help="Generate a default .watchllm.yaml")
    init_p.add_argument(
        "directory",
        nargs="?",
        default=".",
        help="Target directory (default: current directory)",
    )
    init_p.add_argument("--force", action="store_true", help="Overwrite existing config")

    # evaluate
    eval_p = sub.add_parser("evaluate", help="Evaluate a file through the kernel")
    eval_p.add_argument("file", nargs="?", default=None, help="Path to source file")
    eval_p.add_argument("--stdin", action="store_true", help="Read from stdin")
    eval_p.add_argument("--mode", choices=["enforce", "shadow"], default=None)
    eval_p.add_argument("--language", choices=["js", "ts"], default=None)

    # status
    sub.add_parser("status", help="Check health of all WatchLLM subsystems")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if not args.command:
        parser.print_help()
        return 0

    if args.command == "init":
        return cmd_init(args)
    if args.command == "evaluate":
        return cmd_evaluate(args)
    if args.command == "status":
        return cmd_status(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
